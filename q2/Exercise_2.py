count = 10
# Variable 'count' starts at 10
while count >= 1:
    print(count)
    count -= 1
# While the value of 'count' is more than or equal to 10, it prints the current value of 'count' then decreases it by one.
print("Time is up!")
# "Time is up!" is printed when value of 'count' is less than 1.
